"""Prints the A2UI reference agents get (tools/tasks/vendor/a2ui.sh): Paddock's rules
(a2ui-reference-rules.md), then the v1.0 basic catalog's schemas as A2UI's agent SDK renders them
for a model writing JSON messages (DirectJsonFormat). Run with the SDK of the pinned release.

    python3 -I a2ui-reference.py RULES TAG
"""
import sys

from a2ui.core.basic_catalog import BasicCatalog
from a2ui.core.schema import ProtocolVersion
from a2ui.inference_formats.direct_json.format import DirectJsonFormatFactory
from a2ui.processor import A2uiGenerator, CatalogConfig

rules, tag = sys.argv[1], sys.argv[2]
catalog = BasicCatalog(ProtocolVersion.V1_0)
generator = A2uiGenerator([CatalogConfig(catalog)], inference_format_factory=DirectJsonFormatFactory())
snippet = generator.create_processor({"1.0": {"supportedCatalogIds": [catalog.catalog_id]}}).prompt_snippet
# The SDK's response rules are for chat agents (tags, conversational text); Paddock's come first.
marker = "---BEGIN A2UI JSON SCHEMA---"
if marker not in snippet:
    sys.exit("the SDK's prompt has no schema section: its format changed")
with open(rules, encoding="utf-8") as f:
    sys.stdout.write(f.read().rstrip() + "\n\n")
sys.stdout.write(f"<!-- Generated by tools/tasks/vendor/a2ui.sh from a2ui-agent-sdk at A2UI {tag}. -->\n\n")
sys.stdout.write(snippet[snippet.index(marker):].rstrip() + "\n")
